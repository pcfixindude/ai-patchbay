export function portsForComponent(componentId: string) {
  return ports.filter((port) => port.componentId === componentId);
}

export function searchComponents(query: string) {
  const terms = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!terms.length) return components;
  return components.filter((component) => {
    const haystack = [component.name, component.shortName, component.description, component.componentType, ...component.tags]
      .join(" ")
      .toLowerCase();
    return terms.every((term) => haystack.includes(term));
  });
}
